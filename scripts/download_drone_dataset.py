"""Download a drone-detection YOLO dataset from HuggingFace and write data.yaml.

Default dataset: lgrzybowski/seraphim-drone-detection-dataset (CC BY 4.0)
  - 83,483 images, 1 class (`drone`)
  - 640x640 padded, YOLO format
  - Aggregated from 23 open-source drone collections (rotary, FPV, fixed-wing)

The dataset is stored as zipped batches on HuggingFace; this script downloads
the snapshot, extracts every batch in place, and emits a YOLO-compatible
`data.yaml` pointing at train/test splits.

Subsequent runs are idempotent — already-downloaded files are skipped, and
already-extracted zips are not re-extracted (we leave a sentinel marker).

Usage:
    python scripts/download_drone_dataset.py
    python scripts/download_drone_dataset.py --out datasets/seraphim_drone
    python scripts/download_drone_dataset.py --repo other/repo --classes drone
"""

from __future__ import annotations

import argparse
import sys
import time
import zipfile
from pathlib import Path

DEFAULT_REPO = "lgrzybowski/seraphim-drone-detection-dataset"
DEFAULT_OUT = Path("datasets/seraphim_drone")


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--repo", default=DEFAULT_REPO, help="HuggingFace dataset repo id")
    p.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Local directory to extract into")
    p.add_argument(
        "--classes",
        nargs="+",
        default=["drone"],
        help="Class names in id order (must match label .txt class indices)",
    )
    p.add_argument(
        "--train-subdir",
        default="train",
        help="Sub-directory containing train/images and train/labels",
    )
    p.add_argument(
        "--val-subdir",
        default="test",
        help="Sub-directory containing val images & labels (Seraphim ships only train+test)",
    )
    p.add_argument(
        "--skip-download",
        action="store_true",
        help="Don't re-fetch from HF, just (re)write data.yaml against existing files",
    )
    return p.parse_args()


def _human(n_bytes: int) -> str:
    units = ["B", "KB", "MB", "GB", "TB"]
    f = float(n_bytes)
    for u in units:
        if f < 1024 or u == units[-1]:
            return f"{f:.1f} {u}"
        f /= 1024
    return f"{f:.1f} {units[-1]}"


def _download(repo_id: str, out_dir: Path) -> Path:
    from huggingface_hub import snapshot_download

    out_dir.mkdir(parents=True, exist_ok=True)
    print(f"[download] repo='{repo_id}'  ->  {out_dir.resolve()}")
    print("[download] this can take a while (multi-GB). Progress streams below.\n", flush=True)
    t0 = time.time()
    repo_path = Path(
        snapshot_download(
            repo_id=repo_id,
            repo_type="dataset",
            local_dir=str(out_dir),
        )
    )
    dt = time.time() - t0
    print(f"\n[download] done in {dt:.1f}s  -> {repo_path}", flush=True)
    return repo_path


def _extract_zips(root: Path) -> None:
    zips = sorted(root.rglob("*.zip"))
    if not zips:
        print(f"[extract] no zip files under {root} — assuming already extracted")
        return
    print(f"[extract] found {len(zips)} zip files. Extracting...")
    for i, z in enumerate(zips, 1):
        marker = z.with_suffix(z.suffix + ".extracted")
        if marker.exists():
            print(f"  [{i}/{len(zips)}] skip (already extracted): {z.name}")
            continue
        try:
            with zipfile.ZipFile(z) as zf:
                zf.extractall(z.parent)
            marker.write_text("ok")
            z.unlink()
            print(f"  [{i}/{len(zips)}] extracted: {z.relative_to(root)}")
        except zipfile.BadZipFile:
            print(f"  [{i}/{len(zips)}] BAD ZIP, skipped: {z.name}", file=sys.stderr)


def _count(root: Path, sub: str, kind: str) -> int:
    p = root / sub / kind
    if not p.exists():
        return 0
    if kind == "images":
        return sum(1 for _ in p.rglob("*.jpg")) + sum(1 for _ in p.rglob("*.png"))
    return sum(1 for _ in p.rglob("*.txt"))


def _write_data_yaml(root: Path, train_sub: str, val_sub: str, classes: list[str]) -> Path:
    yaml_path = root / "data.yaml"
    body = (
        f"# Auto-generated by scripts/download_drone_dataset.py\n"
        f"path: {root.resolve()}\n"
        f"train: {train_sub}/images\n"
        f"val: {val_sub}/images\n"
        f"nc: {len(classes)}\n"
        f"names: {classes}\n"
    )
    yaml_path.write_text(body)
    print(f"[yaml] wrote {yaml_path}")
    print(body)
    return yaml_path


def main() -> int:
    args = parse_args()
    out_dir: Path = args.out

    if not args.skip_download:
        _download(args.repo, out_dir)

    _extract_zips(out_dir)

    n_train_img = _count(out_dir, args.train_subdir, "images")
    n_train_lbl = _count(out_dir, args.train_subdir, "labels")
    n_val_img = _count(out_dir, args.val_subdir, "images")
    n_val_lbl = _count(out_dir, args.val_subdir, "labels")
    print("[stats]")
    print(f"  {args.train_subdir}: {n_train_img} images, {n_train_lbl} labels")
    print(f"  {args.val_subdir}: {n_val_img} images, {n_val_lbl} labels")

    if n_train_img == 0:
        print("[error] no training images found — extraction or layout problem", file=sys.stderr)
        return 1

    _write_data_yaml(out_dir, args.train_subdir, args.val_subdir, args.classes)
    print("\n[done] dataset is ready. Next:")
    print(f"  make train-drone DATA={out_dir}/data.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
